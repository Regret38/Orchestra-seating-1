import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('물체 크기·이름 변경과 복제·저장·파일 복원·출력, 준비 수량 유지', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toContainText('(예시)');
  await page.getByRole('button', { name: '배치 목록', exact: true }).click();
  await page.getByLabel('새 배치 이름').fill('물체 테스트');
  await page.getByRole('button', { name: '빈 무대로 만들기' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: '기타 물체', exact: true }).click();
  await page.getByLabel('추가할 물체 이름').fill('그랜드 피아노');
  await page.getByRole('button', { name: '무대에 추가', exact: true }).click();
  await page.getByLabel('물체 이름', { exact: true }).fill('피아노 앞 공간');
  await page.getByLabel('물체 가로').fill('400');
  await page.getByLabel('물체 세로').fill('220');
  await page.getByLabel('회전 각도').fill('45');
  await page.getByRole('button', { name: '복제', exact: true }).click();
  await page.getByRole('button', { name: '준비 수량', exact: true }).click();
  for (const k of ['stands', 'chairs', 'benches']) await expect(page.getByRole('complementary').getByTestId(`total-${k}`)).toHaveText('0개');
  await page.getByRole('button', { name: '메모리에 저장', exact: true }).click();
  await expect(page.getByRole('button', { name: '메모리에 저장', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: '출력·내보내기' }).click();
  await expect(page.locator('.output-preview canvas')).toHaveCount(1);
  const event = page.waitForEvent('download');
  await page.getByRole('button', { name: 'JSON 내보내기', exact: true }).click();
  const download = await event;
  const text = await readFile((await download.path())!, 'utf8');
  const file = JSON.parse(text);
  expect(file.layout.data.items).toHaveLength(2);
  expect(file.layout.data.items[0]).toMatchObject({ kind: 'object', objectLabel: '피아노 앞 공간', objectWidth: 400, objectHeight: 220, rotation: 45 });
  await page.getByRole('button', { name: '닫기', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('heading', { level: 1 })).toContainText('(예시)');
  await page.locator('input[type=file]').setInputFiles({ name: 'objects.json', mimeType: 'application/json', buffer: Buffer.from(text) });
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('물체 테스트');
  for (const k of ['stands', 'chairs', 'benches']) await expect(page.getByRole('complementary').getByTestId(`total-${k}`)).toHaveText('0개');
  expect(errors).toEqual([]);
});
